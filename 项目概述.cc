/*
readv分块接收操作
核心关键点： 为什么muduo库性能在大块数据的pingpong测试中比libevent高了近3倍
  muduo中使用readv分块接收，一次IO取出了socket缓冲区所有数据
  而libevent是循环每次接收4096字节数据

核心关键点：
 muduo库中，epoll监控时时间触发模式使用的时水平触发，而不是边缘触发
 水平触发：只有socket接收缓冲区中的数据大于高水位标记(1B)就会触发事件
 边缘触发：只要新数据到来的时候才会触发事件

 强制要求程序员在一次事件触发中，处理完所有数据；减少了事件触发数量
 
*/

/*
  套接字选项设置：
  TCP_NODELAY: 延迟发送机制
   延迟发送机制：调用send的时候这条数据并不会立即被封装发送，而是将数据放到缓冲区等一会发送，避免大量的小数据I/O，等一会可以尽可能地将小数据攒成
         大数据一次IO完成发送减少IO次数，提高效率
    这个机制，默认时开启的；在套接字选项设置中，开启该选项，实际上是关闭该机制

  延迟应答机制&捎带应答机制：接收端接收到数据之后，并不会立即进行确认应答，而是等一会
      延迟应答时考虑上层取出数据进行处理后，大概率胡立即进行响应，这时候就会把确认应答信息顺便放到这个响应地数据头中进行确认应答
  
  SOCK_REUSEADDR选项: 地址重用选项    通常用在服务端
    TCP通信中，主动关闭方，关闭连接后，会进入TIME_WAIT状态，持续2MSL时间，保护通信
    但是，这个状态导致套接字资源没有 完全被释放，至少该套接字地地址和端口被占用，新连接无法使用改地址信息进行绑定

    地址重用选项就是解决这个问题的：让套接字可以立即绑定TIME_WAIT状态地套接字地址信息。
    该选项默认关闭，需要我们程序员手动开启  (对于服务端，是必选选项)
    1.当服务器关闭之后，服务器的地址和端口会进入TIME_WAIT状态，在这个状态下，如果再次启动服务器，系统会认为这个地址和端口正在被使用，无法绑定成功
    2.开启地址复用选项之后，即使在TIME_WAIT状态下，也能够成功绑定地址和端口

    SOCK_REUSEPORT选项：端口重用选项  该选项允许多个套接字绑定同一个地址和端口，前提是这些套接字都设置了SO_REUSEPORT选项
    常用于socket负载均衡。
      通常编程的时候创建套接字，绑定地址，开始监听，获取新连接
       若新连接非常多，非常频繁，获取新连接甚至会成为性能瓶颈
       因此就要负载均衡，将获取新连接操作，分发到不同地线程中处理
       服务端就可以开启端口重用，在同一个地址端口上创建多个监听套接字，在不同的线程中进行监控
       内核中，会发现有多个套接字使用相同的地址信息，就会在新连接到来的时候自动负载均衡

    SOCK_KEEPALIVE选项：连接保活机制
       1.该选项默认是关闭的
       2.选项作用：
         让tcp通信两端，在长时间无通信(7200s)的情况下，每隔一会(75s)给对方发送一个保活探测数据包，若对方无响应，则在多次探测后(9次)，认为网络连接断开
       3.这些选项都是可以设置的，也是通过套接字选项配置进行设置

*/

/*
应用层协议：LV格式
L:length,描述数据长度
V：value,实际的数据

缓冲区设计：前置的预留空间，后置的数据空间
  1.预留空间：在缓冲区的前面预留8B空间，专门用来存储数据长度
  2.数据空间：在缓冲区的后面存储实际的数据

  设计原因：
    1.在网络通信中，数据是以字节流的形式进行传输的，没有明确的边界，因此需要一种方式来标识每条消息的长度，以便接收方能够正确地解析消息
    2.通过在缓冲区前面预留8B空间来存储数据长度，可以让接收方在读取数据时，先读取这8B来获取消息的长度，然后再根据这个长度来读取实际的数据，这样就能够正确地解析每条消息了      
*/